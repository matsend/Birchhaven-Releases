import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {readPatch} from './read-patch.mjs';
import {splitPatch} from './split-patch.mjs';
const hash = b => createHash('sha256').update(b).digest('hex');
test('large release patches round-trip through bounded transfer parts', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'birchhaven-split-'));
  t.after(() => fs.rmSync(dir, {recursive:true, force:true}));
  const patch = {version:'7.22.0', files:[{path:'dist/client/example.js', gzip:'x'.repeat(300000)}], remove:[]};
  const input = path.join(dir, 'original.json');
  fs.writeFileSync(input,JSON.stringify(patch));
  const result = splitPatch(input,path.join(dir,'parts'));
  assert.equal(result.parts,3);
  assert.deepEqual(readPatch(result.filename,result.patchSha256,result.version),patch);
});
test('multipart patches reject missing, altered, reordered and out-of-directory parts', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'birchhaven-patch-'));
  t.after(() => fs.rmSync(dir, {recursive:true, force:true}));
  const patch = {version:'7.22.0', files:[{path:'dist/client/example.js', text:'åäö'}], remove:[]};
  const bytes = Buffer.from(JSON.stringify(patch));
  const halves = [bytes.subarray(0,31), bytes.subarray(31)];
  const index = {format:2, version:patch.version, size:bytes.length, sha256:hash(bytes), parts:halves.map((b,i)=>({name:`7.22.0.part-00${i+1}`, size:b.length, sha256:hash(b)}))};
  const file = path.join(dir, '7.22.0.json');
  const write = value => { const b = Buffer.from(JSON.stringify(value)); fs.writeFileSync(file,b); return hash(b); };
  halves.forEach((b,i)=>fs.writeFileSync(path.join(dir,index.parts[i].name),b));
  assert.deepEqual(readPatch(file,write(index),patch.version),patch);
  assert.deepEqual(readPatch(file,write(patch),patch.version),patch);
  assert.throws(()=>readPatch(file, '0'.repeat(64),patch.version),/checksum/);
  assert.throws(()=>readPatch(file,write({...index,parts:[...index.parts].reverse()}),patch.version),/Invalid patch part/);
  assert.throws(()=>readPatch(file,write({...index,parts:[{...index.parts[0],name:'../outside'},index.parts[1]]}),patch.version),/Invalid patch part/);
  assert.throws(()=>readPatch(file,write({...index,size:41*1024*1024}),patch.version),/Invalid multipart/);
  assert.throws(()=>readPatch(file,write({...index,sha256:'0'.repeat(64)}),patch.version),/Joined patch checksum/);
  fs.writeFileSync(path.join(dir,index.parts[0].name),'altered');
  assert.throws(()=>readPatch(file,write(index),patch.version),/Patch part checksum/);
  fs.unlinkSync(path.join(dir,index.parts[0].name));
  assert.throws(()=>readPatch(file,write(index),patch.version),/ENOENT/);
});
